"""Offline extraction or source-authenticated replay of Zeek JSON conn.log.
Run from python-service: python tools/replay_zeek.py --help.
The source key is read from AEGIS_LOG_SOURCE_KEY, never a command argument.
"""
import argparse
import json
import os
from pathlib import Path
import sys
import urllib.error
import urllib.parse
import urllib.request
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.flow_features import normalize_zeek, FlowValidationError

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--capture-id", required=True, help="Stable ID reused for retries; unique for distinct capture sessions")
    parser.add_argument("--endpoint", help="Optional full /api/v1/flows/ingest URL; omit for offline JSONL extraction")
    parser.add_argument("--simulated", action="store_true", help="Mark synthetic fixtures; do not mix them into research results")
    args = parser.parse_args(argv)
    if not args.capture_id.strip() or len(args.capture_id) > 200:
        parser.error("capture-id must be nonempty and at most 200 characters")
    key = os.getenv("AEGIS_LOG_SOURCE_KEY")
    if args.endpoint:
        url = urllib.parse.urlsplit(args.endpoint)
        if url.scheme not in {"http", "https"} or not url.hostname or url.username or url.password or url.query or url.fragment:
            parser.error("Use a plain HTTP(S) endpoint without credentials, query or fragment")
        if url.scheme != "https" and url.hostname not in {"localhost", "127.0.0.1", "::1"}:
            parser.error("Remote source keys require HTTPS")
        if not key:
            parser.error("Set AEGIS_LOG_SOURCE_KEY in the environment")
    processed = 0
    shadow_counts = {}
    try:
        with args.input.open(encoding="utf-8", newline="") as stream:
            for line_number, line in enumerate(stream, 1):
                raw = line.removesuffix("\n").removesuffix("\r")
                if not raw.strip():
                    continue
                if raw.startswith("#"):
                    raise FlowValidationError("Zeek TSV is unsupported; produce JSON conn.log with LogAscii::use_json=T")
                normalized = normalize_zeek(raw)
                if args.endpoint:
                    body = json.dumps({"raw_record": raw, "capture_id": args.capture_id,
                                       "is_simulated": args.simulated}).encode()
                    request = urllib.request.Request(args.endpoint, data=body, method="POST", headers={
                        "Content-Type": "application/json", "Authorization": f"Bearer {key}"})
                    # Never follow redirects with a source credential.
                    class NoRedirect(urllib.request.HTTPRedirectHandler):
                        def redirect_request(self, *unused):
                            return None
                    with urllib.request.build_opener(NoRedirect()).open(request, timeout=15) as response:
                        result = json.load(response)
                        if not isinstance(result, dict):
                            raise ValueError("Invalid server response")
                    shadow = result.get("shadow_analysis")
                    status = shadow.get("status", "not_assessed") if isinstance(shadow, dict) else "not_assessed"
                    shadow_counts[status] = shadow_counts.get(status, 0) + 1
                    print(json.dumps({"line": line_number, **result}, allow_nan=False))
                else:
                    print(json.dumps({"capture_id": args.capture_id, "is_simulated": args.simulated,
                                      **normalized}, allow_nan=False))
                processed += 1
    except (ValueError, OSError, UnicodeError, urllib.error.URLError) as exc:
        print(f"Replay stopped after {processed} accepted/output records: {type(exc).__name__}. Check input and service configuration. Previously stored records remain; rerun with the same capture ID.", file=sys.stderr)
        return 1
    if args.endpoint:
        print(f"Processed {processed} flow records; shadow states: {json.dumps(shadow_counts)}. No confirmed threat or incident was generated by flow replay.", file=sys.stderr)
    else:
        print(f"Processed {processed} flow records; offline extraction only, no model prediction.", file=sys.stderr)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
